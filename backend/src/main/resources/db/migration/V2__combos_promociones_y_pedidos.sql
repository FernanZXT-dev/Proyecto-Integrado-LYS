-- Amplía V1 conservando las tablas y datos existentes.
CREATE TABLE producto_personalizaciones (
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    opcion VARCHAR(80) NOT NULL,
    PRIMARY KEY (producto_id, opcion)
);

CREATE TABLE combos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500),
    precio NUMERIC(10,2) NOT NULL CHECK (precio >= 0.01),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE combo_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    combo_id BIGINT NOT NULL REFERENCES combos(id),
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    cantidad INTEGER NOT NULL CHECK (cantidad BETWEEN 1 AND 50),
    UNIQUE (combo_id, producto_id)
);

CREATE TABLE promociones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500),
    porcentaje_descuento NUMERIC(5,2) NOT NULL CHECK (porcentaje_descuento > 0 AND porcentaje_descuento <= 100),
    inicio TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    fin TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    producto_id BIGINT REFERENCES productos(id),
    combo_id BIGINT REFERENCES combos(id),
    CHECK (fin > inicio),
    CHECK ((producto_id IS NOT NULL) <> (combo_id IS NOT NULL))
);

CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    cliente_id BIGINT REFERENCES clientes(id),
    registrado_por_id BIGINT REFERENCES usuarios(id),
    modalidad VARCHAR(20) NOT NULL CHECK (modalidad IN ('LOCAL','RECOJO','DELIVERY')),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('RECIBIDO','EN_PREPARACION','CANCELADO')),
    nombre_contacto VARCHAR(100) NOT NULL,
    telefono VARCHAR(20),
    mesa VARCHAR(20),
    direccion VARCHAR(300),
    referencia VARCHAR(200),
    subtotal NUMERIC(16,2) NOT NULL CHECK (subtotal >= 0),
    costo_delivery NUMERIC(16,2) NOT NULL CHECK (costo_delivery >= 0),
    total NUMERIC(16,2) NOT NULL CHECK (total = subtotal + costo_delivery),
    creado_en TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    actualizado_en TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CHECK ((cliente_id IS NOT NULL) <> (registrado_por_id IS NOT NULL)),
    CHECK (modalidad <> 'LOCAL' OR length(trim(mesa)) > 0 AND mesa IS NOT NULL),
    CHECK (modalidad <> 'DELIVERY' OR length(trim(direccion)) > 0 AND direccion IS NOT NULL),
    CHECK (modalidad = 'LOCAL' OR telefono IS NOT NULL AND length(trim(telefono)) > 0)
);

CREATE TABLE pedido_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
    producto_id BIGINT REFERENCES productos(id),
    combo_id BIGINT REFERENCES combos(id),
    promocion_id BIGINT REFERENCES promociones(id),
    nombre VARCHAR(100) NOT NULL,
    contenido_combo VARCHAR(3000),
    cantidad INTEGER NOT NULL CHECK (cantidad BETWEEN 1 AND 50),
    precio_base NUMERIC(16,2) NOT NULL CHECK (precio_base >= 0),
    porcentaje_descuento NUMERIC(5,2) NOT NULL CHECK (porcentaje_descuento BETWEEN 0 AND 100),
    precio_unitario NUMERIC(16,2) NOT NULL CHECK (precio_unitario >= 0),
    total NUMERIC(16,2) NOT NULL CHECK (total = precio_unitario * cantidad),
    indicaciones VARCHAR(300),
    CHECK ((producto_id IS NOT NULL) <> (combo_id IS NOT NULL))
);

CREATE TABLE pedido_item_personalizaciones (
    pedido_item_id BIGINT NOT NULL REFERENCES pedido_items(id),
    opcion VARCHAR(120) NOT NULL,
    PRIMARY KEY (pedido_item_id, opcion)
);

CREATE INDEX idx_combo_items_producto ON combo_items(producto_id);
CREATE INDEX idx_promociones_producto ON promociones(producto_id);
CREATE INDEX idx_promociones_combo ON promociones(combo_id);
CREATE INDEX idx_pedidos_cliente_fecha ON pedidos(cliente_id, creado_en DESC);
CREATE INDEX idx_pedido_items_pedido ON pedido_items(pedido_id);
